def pilih_transportasi(jarak_km: float,
                       cuaca: str,
                       punya_mobil: bool) -> str:
    """
    Menentukan moda transportasi terbaik berdasarkan:
        - jarak_km   : jarak dari rumah ke kantor (km)
        - cuaca     : 'cerah', 'hujan', atau 'berawan'
        - punya_mobil: True bila ada mobil pribadi, False bila tidak

    Returns
    -------
    str
        Rekomendasi transportasi: 'jalan kaki', 'sepeda',
        'kendaraan umum', atau 'mobil'.
    """
    cuaca = cuaca.lower()

    if jarak_km < 3:
        return "jalan kaki"

    elif jarak_km <= 10:
        if cuaca == "cerah":
            return "sepeda"
        else:
            if punya_mobil:
                return "mobil"
            else:
                return "kendaraan umum"

    else:
        if cuaca == "hujan":

            return "kendaraan umum"
        else:
            if punya_mobil:
                return "mobil"
            else:
                return "kendaraan umum"

if __name__ == "__main__":
    contoh = [
        (2.5, "cerah", False),
        (5,   "hujan", False),
        (8,   "berawan", True),
        (12,  "cerah", True),
        (15,  "hujan", False),
    ]

    for i, (j, c, m) in enumerate(contoh, 1):
        rekom = pilih_transportasi(j, c, m)
        print(f"Contoh {i}: jarak={j} km, cuaca={c}, mobil={m} → {rekom}")